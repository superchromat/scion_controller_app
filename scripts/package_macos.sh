#!/usr/bin/env bash
#
# Build → Developer ID sign → notarize → staple the macOS app for beta testers.
#
# Output (VERSION comes from the git tag, see set_version.sh):
#   build/scion-<VERSION>-macos.dmg   the thing to hand out: drag-to-Applications
#   build/scion-<VERSION>-macos.zip   same app, for people who prefer a zip
#
# Both are signed with a Developer ID cert, notarized by Apple, and have the
# notarization ticket stapled into them, so they open on a stranger's Mac with a
# plain "are you sure you want to open it" — no Gatekeeper override, no
# right-click-Open, no System Settings → Privacy & Security detour, and no
# network needed at first launch (that's what stapling buys).
#
# ---------------------------------------------------------------------------
# ONE-TIME SETUP
#
#   1. Developer ID Application cert + private key in the login keychain.
#      (Verify: `security find-identity -v -p codesigning` shows it.)
#      If the cert is present but "0 valid identities", the G2 intermediate is
#      missing — install it:
#        curl -fsSLO https://www.apple.com/certificateauthority/DeveloperIDG2CA.cer
#        security add-certificates DeveloperIDG2CA.cer
#
#   2. Store notary credentials as a keychain profile (needs an app-specific
#      password from appleid.apple.com → Sign-In & Security → App-Specific Passwords):
#        xcrun notarytool store-credentials scion-notary \
#          --apple-id "YOU@example.com" --team-id DJ7F26GRG8 --password "xxxx-xxxx-xxxx-xxxx"
#
#   3. (Optional, avoids a codesign GUI prompt per run) authorize the key for
#      command-line tools — enter your macOS login password when asked:
#        security set-key-partition-list -S apple-tool:,apple:,codesign: -s \
#          -k "$(read -rsp 'login password: ' p; echo "$p")" ~/Library/Keychains/login.keychain-db
#
# ENV KNOBS
#   SKIP_NOTARIZE=1   build/sign/package but skip the two Apple round-trips.
#                     For iterating on the DMG layout only — the result is NOT
#                     distributable.
# ---------------------------------------------------------------------------
set -euo pipefail

# The bundle name, which is what Finder shows. Must match PRODUCT_NAME in
# macos/Runner/Configs/AppInfo.xcconfig — that is what the build actually names
# the .app, and a mismatch here fails at the first `ditto`.
APP_NAME="SCION Controller"
# Filename stem for the zip and dmg, kept separate and space-free: these get
# served over HTTP, and "SCION%20Controller-0.9.1-macos.dmg" is nobody's friend.
ARTIFACT="scion"
IDENTITY="Developer ID Application: Superchromat Pty. Ltd. (DJ7F26GRG8)"
NOTARY_PROFILE="scion-notary"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
ENT="macos/Runner/Release.entitlements"
APP="build/macos/Build/Products/Release/${APP_NAME}.app"

echo "==> Stamping version from git"
"$ROOT/scripts/set_version.sh"

# pubspec now holds "<semver>+<build>". Artifacts are named with the semver only
# — that is the number a tester will quote back at you — while the build number
# rides along inside the bundle (CFBundleVersion) for exact identification.
PUBSPEC_VERSION="$(sed -n 's/^version:[[:space:]]*//p' pubspec.yaml | head -1)"
VERSION="${PUBSPEC_VERSION%%+*}"
BUILD_NUMBER="${PUBSPEC_VERSION##*+}"
if [[ -z "$VERSION" ]]; then
  echo "package_macos: could not read version from pubspec.yaml" >&2
  exit 1
fi

ZIP="build/${ARTIFACT}-${VERSION}-macos.zip"
DMG="build/${ARTIFACT}-${VERSION}-macos.dmg"
DMG_RW="build/.${ARTIFACT}-${VERSION}-rw.dmg"
STAGE="build/.dmg-staging"
VOLNAME="SCION ${VERSION}"
# Committed artwork, regenerated by `python3 tool/gen_dmg_background.py`. The
# icon coordinates in the AppleScript below are drawn into it — change one,
# change both.
DMG_BACKGROUND="macos/dmg/background.tiff"

# A previously signed-and-launched bundle picks up the SIP-protected
# com.apple.provenance xattr, after which Xcode's copy step fails with
# "Operation not permitted" (EPERM) when overwriting Contents/Resources.
# Scoped to build/macos so the release artifacts at build/ are never touched.
echo "==> Clearing stale macOS build tree"
rm -rf "$ROOT/build/macos"

# The unversioned artifact this script used to emit. Left in place it sits next
# to the versioned ones looking equally shippable, which is how a stale build
# ends up in a tester's hands.
rm -f "build/${ARTIFACT}-macos.zip"

echo "==> Building release ${VERSION}+${BUILD_NUMBER}"
flutter build macos --release

# Sign inside-out: nested dylibs and frameworks first, then the app bundle.
# Hardened runtime (--options runtime) and a secure timestamp are required for
# notarization. Entitlements go on the app bundle ONLY — a framework signed with
# the sandbox entitlement is a notarization failure.
echo "==> Signing nested code"
while IFS= read -r -d '' f; do
  codesign --force --options runtime --timestamp --sign "$IDENTITY" "$f"
done < <(find "$APP/Contents/Frameworks" -type f -name "*.dylib" -print0 2>/dev/null)

while IFS= read -r -d '' f; do
  codesign --force --options runtime --timestamp --sign "$IDENTITY" "$f"
done < <(find "$APP/Contents/Frameworks" -maxdepth 1 -name "*.framework" -print0 2>/dev/null)

echo "==> Signing app bundle"
codesign --force --options runtime --timestamp \
  --entitlements "$ENT" --sign "$IDENTITY" "$APP"
codesign --verify --deep --strict --verbose=2 "$APP"

# Nothing may be left unsigned or ad-hoc signed: notarization rejects the whole
# submission over a single stray Mach-O. Cheaper to catch it here than after a
# five-minute round-trip.
echo "==> Checking every Mach-O in the bundle is Developer ID signed"
while IFS= read -r f; do
  # Capture and match, rather than `codesign ... | grep -q`. Under `pipefail`
  # that pipeline reports failure for a *signed* binary: grep -q exits at the
  # first match, codesign dies of SIGPIPE still writing the remaining lines, and
  # pipefail surfaces its 141 as the pipeline's status. Races on output length,
  # so it fails intermittently — which is worse than failing always.
  desc="$(codesign -dv --verbose=2 "$f" 2>&1 || true)"
  case "$desc" in
    *"Authority=Developer ID Application"*) ;;
    *)
      echo "package_macos: NOT Developer ID signed: $f" >&2
      exit 1
      ;;
  esac
done < <(find "$APP" -type f -exec sh -c 'file -b "$1" | grep -q "Mach-O" && echo "$1"' _ {} \;)

echo "==> Zipping for notarization"
rm -f "$ZIP"
ditto -c -k --sequesterRsrc --keepParent "$APP" "$ZIP"

if [[ "${SKIP_NOTARIZE:-0}" == "1" ]]; then
  echo "==> SKIP_NOTARIZE=1 — not submitting the app (result is NOT distributable)"
else
  echo "==> Notarizing the app (a few minutes)"
  xcrun notarytool submit "$ZIP" --keychain-profile "$NOTARY_PROFILE" --wait

  # Staple the app itself, not just the DMG: once a tester drags it to
  # /Applications it is on its own, and a stapled bundle validates with no
  # network round-trip to Apple.
  echo "==> Stapling the ticket to the app"
  xcrun stapler staple "$APP"
  xcrun stapler validate "$APP"

  echo "==> Repackaging the stapled app"
  rm -f "$ZIP"
  ditto -c -k --sequesterRsrc --keepParent "$APP" "$ZIP"
fi

echo "==> Gatekeeper assessment of the app"
spctl -a -vvv --type execute "$APP" || true

# ---------------------------------------------------------------------------
# DMG: the app beside a symlink to /Applications, so the install gesture is
# self-evident (drag left onto right).
# ---------------------------------------------------------------------------
echo "==> Staging the DMG contents"
rm -rf "$STAGE" "$DMG_RW" "$DMG"
mkdir -p "$STAGE"
# ditto, not cp: preserves the signature, the stapled ticket and every xattr.
ditto "$APP" "$STAGE/${APP_NAME}.app"
ln -s /Applications "$STAGE/Applications"

# The drag-to-install arrow. A dot-directory so it does not show up as a third
# item in the window.
HAVE_BACKGROUND=0
if [[ -f "$DMG_BACKGROUND" ]]; then
  mkdir -p "$STAGE/.background"
  cp "$DMG_BACKGROUND" "$STAGE/.background/background.tiff"
  HAVE_BACKGROUND=1
else
  echo "    (no $DMG_BACKGROUND — run: python3 tool/gen_dmg_background.py)"
fi

# Size to fit with slack — Finder needs room to write the .DS_Store that carries
# the window layout below, and a disk-full there fails silently and ugly.
STAGE_MB="$(du -sm "$STAGE" | cut -f1)"
DMG_MB=$(( STAGE_MB + 100 ))

echo "==> Creating read/write DMG (${DMG_MB} MB)"
hdiutil create -srcfolder "$STAGE" -volname "$VOLNAME" \
  -fs HFS+ -format UDRW -size "${DMG_MB}m" -ov -quiet "$DMG_RW"

echo "==> Laying out the DMG window"
# Read the mount point back rather than assuming /Volumes/$VOLNAME: if a copy of
# this volume is already mounted, macOS appends " 1" and every path below would
# silently point at the wrong image.
ATTACH_OUT="$(hdiutil attach -readwrite -noverify "$DMG_RW")"
DEV="$(printf '%s\n' "$ATTACH_OUT" | grep -Eo '^/dev/disk[0-9]+' | head -1)"
MOUNT_DIR="$(printf '%s\n' "$ATTACH_OUT" | grep -o '/Volumes/.*' | head -1)"
DISK_NAME="$(basename "$MOUNT_DIR")"

# Interpolated rather than inlined so a missing background file degrades to a
# plain window instead of an AppleScript error.
BG_LINE=""
if [[ "$HAVE_BACKGROUND" == "1" ]]; then
  BG_LINE='set background picture of opts to file ".background:background.tiff"'
fi

# Best-effort. Automating Finder needs an Automation grant (System Settings →
# Privacy & Security → Automation) and there is none in a headless/CI context,
# so a failure here costs cosmetics, not correctness: the app and the
# /Applications symlink are both present either way.
if ! osascript <<APPLESCRIPT
tell application "Finder"
  tell disk "$DISK_NAME"
    open
    set current view of container window to icon view
    set toolbar visible of container window to false
    set statusbar visible of container window to false
    set the bounds of container window to {200, 120, 840, 520}
    set opts to the icon view options of container window
    set arrangement of opts to not arranged
    set icon size of opts to 128
    set text size of opts to 13
    $BG_LINE
    set position of item "${APP_NAME}.app" of container window to {160, 158}
    set position of item "Applications" of container window to {480, 158}
    update without registering applications
    delay 2
    close
  end tell
end tell
APPLESCRIPT
then
  echo "    (Finder layout skipped — DMG contents are still correct)"
fi

sync
# The volume can stay busy for a beat after Finder lets go; -force is the
# documented way through and is safe on a scratch image we own.
hdiutil detach "$DEV" -quiet || hdiutil detach "$DEV" -force -quiet

echo "==> Compressing the DMG"
hdiutil convert "$DMG_RW" -format UDZO -imagekey zlib-level=9 -o "$DMG" -quiet
rm -f "$DMG_RW"
rm -rf "$STAGE"

# The DMG is itself a distributable artifact, so it gets its own Developer ID
# signature. Unsigned, Gatekeeper judges it on the quarantine bit alone and the
# tester gets the scary "can't be opened" dialog before ever seeing the app.
echo "==> Signing the DMG"
codesign --force --timestamp --sign "$IDENTITY" "$DMG"
codesign --verify --strict --verbose=2 "$DMG"

if [[ "${SKIP_NOTARIZE:-0}" == "1" ]]; then
  echo "==> SKIP_NOTARIZE=1 — DMG is signed but NOT notarized. Do not distribute."
else
  echo "==> Notarizing the DMG (a few minutes)"
  xcrun notarytool submit "$DMG" --keychain-profile "$NOTARY_PROFILE" --wait

  echo "==> Stapling the ticket to the DMG"
  xcrun stapler staple "$DMG"
  xcrun stapler validate "$DMG"
fi

# What a stranger's Mac actually does: assess the DMG as a thing being opened,
# then the app inside it as a thing being executed. Both must say "accepted"
# with source=Notarized Developer ID.
echo "==> Final verification (as an untrusted Mac would see it)"
echo "--- DMG ---"
spctl -a -vvv --type open --context context:primary-signature "$DMG" || true

VERIFY_OUT="$(hdiutil attach -readonly -nobrowse "$DMG")"
VERIFY_DEV="$(printf '%s\n' "$VERIFY_OUT" | grep -Eo '^/dev/disk[0-9]+' | head -1)"
VERIFY_DIR="$(printf '%s\n' "$VERIFY_OUT" | grep -o '/Volumes/.*' | head -1)"
echo "--- app inside the DMG ---"
spctl -a -vvv --type execute "$VERIFY_DIR/${APP_NAME}.app" || true
xcrun stapler validate "$VERIFY_DIR/${APP_NAME}.app" || true
ls -l "$VERIFY_DIR"
hdiutil detach "$VERIFY_DEV" -quiet || hdiutil detach "$VERIFY_DEV" -force -quiet

echo
echo "==> Done — version ${VERSION} (build ${BUILD_NUMBER})"
echo "    $DMG"
echo "    $ZIP"
